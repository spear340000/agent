import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { SqliteTaskRepository } from '../src/infrastructure/persistence/sqlite-task-repository.ts';
import { LocalFileStorage } from '../src/infrastructure/storage/local-file-storage.ts';
import { SpreadsheetService } from '../src/application/spreadsheet-service.ts';
import { DocumentService } from '../src/application/document-service.ts';
import { DocumentContentService } from '../src/application/document-content-service.ts';
import { RedactionService } from '../src/application/redaction-service.ts';
import { PdfService } from '../src/application/pdf-service.ts';
import { FileService } from '../src/application/file-service.ts';
import { findInvalidCitations } from '../src/application/source-citations.ts';
import { assertPublicHttpUrl } from '../src/tools/public-url.ts';
import { readJson } from '../src/api/http.ts';
import { Readable } from 'node:stream';
import { isAllowedOrigin } from '../src/api/origin-policy.ts';
import { AgentService } from '../src/application/agent-service.ts';
import { TaskEventBus } from '../src/application/task-event-bus.ts';
import ExcelJS from 'exceljs';
import { PDFDocument } from 'pdf-lib';
import { browserAction, computerAction } from '../src/api/contracts.ts';

const testRoot = mkdtempSync(path.join(os.tmpdir(), 'agent-backend-smoke-'));
process.once('exit', () => rmSync(testRoot, { recursive: true, force: true }));
const file = path.join(testRoot, 'test.db');
const tasks = new SqliteTaskRepository(file);
const task = tasks.createTask('Create a backend test');
assert.equal(tasks.getTask(task.id)?.status, 'queued');
for (let index = 0; index < 105; index++) {
  const historyTask = tasks.createTask(`bounded history ${index}`);
  tasks.addEvent(historyTask.id, { type: 'history', title: 'History', message: String(index), status: 'completed' });
  tasks.addArtifact(historyTask.id, { name: `history-${index}`, kind: 'document', mimeType: 'text/plain', content: 'x' });
}
assert.equal(tasks.listTasks().length, 100);
const boundedHistory = tasks.createTask('history boundary');
for (let index = 0; index < 105; index++) {
  tasks.addEvent(boundedHistory.id, { type: 'history', title: 'History', message: String(index), status: 'completed' });
  tasks.addArtifact(boundedHistory.id, { name: `artifact-${index}`, kind: 'document', mimeType: 'text/plain', content: 'x' });
}
assert.equal(tasks.events(boundedHistory.id).length, 100);
assert.equal(tasks.events(boundedHistory.id)[0]?.message, '5');
assert.equal(tasks.artifacts(boundedHistory.id).length, 100);
assert.equal(tasks.artifacts(boundedHistory.id)[0]?.name, 'artifact-5');
const agentForCancellation = new AgentService(tasks, { complete: async () => '' }, {} as never, {} as never, {} as never, new TaskEventBus());
const taskToCancel = tasks.createTask('Cancel this task');
await agentForCancellation.cancel(taskToCancel.id);
assert.equal(tasks.getTask(taskToCancel.id)?.status, 'cancelled');
assert.equal(tasks.events(taskToCancel.id).at(-1)?.type, 'task.cancelled');
const runningTask = tasks.createTask('Cancel in-flight model work');
let modelStarted!: () => void;
let modelSignal: AbortSignal | undefined;
const modelStartedPromise = new Promise<void>(resolve => { modelStarted = resolve; });
const cancellableAgent = new AgentService(tasks, {
  complete: ({ signal }) => new Promise<string>(resolve => {
    modelSignal = signal; modelStarted();
    signal?.addEventListener('abort', () => resolve('{"title":"Report","searchQueries":[],"outline":[]}'), { once: true });
  }),
}, {} as never, {} as never, {} as never, new TaskEventBus());
const runningPromise = cancellableAgent.run(runningTask.id);
await modelStartedPromise;
cancellableAgent.cancel(runningTask.id);
await runningPromise;
assert.equal(modelSignal?.aborted, true);
assert.equal(tasks.getTask(runningTask.id)?.status, 'cancelled');
assert.equal(tasks.getTask(runningTask.id)?.steps[0]?.status, 'cancelled');
tasks.updateTask(task.id, { status: 'running' });
assert.equal(tasks.getTask(task.id)?.status, 'running');
const event = tasks.addEvent(task.id, { type: 'test', title: 'Test', message: 'ok', status: 'completed' });
assert.equal(tasks.events(task.id)[0]?.id, event.id);
const artifact = tasks.addArtifact(task.id, { name: 'test', kind: 'document', mimeType: 'text/plain', content: 'ok' });
assert.equal(tasks.artifact(artifact.id)?.content, 'ok');
tasks.close();
const fileRoot = path.join(testRoot, 'files');
const storage = new LocalFileStorage(fileRoot);
const concurrentFiles = await Promise.all(Array.from({ length: 12 }, (_, index) => storage.save({ name: `parallel-${index}.txt`, mimeType: 'text/plain', content: Buffer.from(String(index)) })));
assert.equal((await Promise.all(concurrentFiles.map(file => storage.get(file.id)))).filter(Boolean).length, concurrentFiles.length);
const limitedFiles = new FileService(storage, { maxUploadBytes: 4 });
await assert.rejects(() => limitedFiles.uploadBase64({ name: 'large.txt', mimeType: 'text/plain', base64: Buffer.from('12345').toString('base64') }), /maximum upload size/);
assert.deepEqual(findInvalidCitations('Finding [W9] is unsupported; see [PDF1].', ['W1', 'PDF1']), ['W9']);
assert.deepEqual(findInvalidCitations('Finding [W1] and [PDF1].', ['W1', 'PDF1']), []);
await assert.rejects(() => assertPublicHttpUrl('http://127.0.0.1/admin'), /private or local/);
await assert.rejects(() => assertPublicHttpUrl('http://localhost:8787/'), /private or local/);
const oversizedJson = Object.assign(Readable.from([Buffer.from('12345')]), { headers: {} });
await assert.rejects(() => readJson(oversizedJson as never, 4), /maximum request body/);
const exactLimitJson = Object.assign(Readable.from([Buffer.from('{}  ')]), { headers: {} });
assert.deepEqual(await readJson(exactLimitJson as never, 4), {});
const scalarJson = Object.assign(Readable.from([Buffer.from('null')]), { headers: {} });
await assert.rejects(() => readJson(scalarJson as never), /JSON object/);
assert.equal(isAllowedOrigin('http://evil.example', ['http://localhost:5173']), false);
assert.equal(isAllowedOrigin('http://localhost:5173', ['http://localhost:5173']), true);
assert.throws(() => browserAction({ kind: 'navigate' }), /url must be a string/);
assert.throws(() => browserAction({ kind: 'click', selector: '' }), /selector is required/);
assert.throws(() => computerAction({ action: { kind: 'click', x: -1, y: 4 } }), /coordinates must be between 0 and 20000/);
const workbook = new ExcelJS.Workbook(); workbook.addWorksheet('Sheet1').getCell('A1').value = 'before';
const input = await storage.save({ name: 'input.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', content: Buffer.from(await workbook.xlsx.writeBuffer()) });
const spreadsheet = new SpreadsheetService(storage);
const edited = await spreadsheet.edit({ fileId: input.id, outputName: 'edited.xlsx', operations: [{ kind: 'setCell', sheet: 'Sheet1', cell: 'A1', value: 'after' }, { kind: 'setFormula', sheet: 'Sheet1', cell: 'B1', formula: '=1+1' }] });
const loaded = new ExcelJS.Workbook(); await loaded.xlsx.load((await storage.read(edited.id)).content as never);
assert.equal(loaded.getWorksheet('Sheet1')?.getCell('A1').value, 'after');
assert.equal((loaded.getWorksheet('Sheet1')?.getCell('B1').value as { formula?: string }).formula, '1+1');
const document = await new DocumentService(storage).create({ outputName: 'draft.docx', title: 'Test title', paragraphs: ['Test paragraph'] });
assert.equal(document.name, 'draft.docx');
assert.ok((await storage.read(document.id)).content.length > 0);
const replaced = await new DocumentService(storage).replaceText({ fileId: document.id, outputName: 'replaced.docx', replacements: [{ find: 'Test paragraph', replace: 'Updated paragraph' }] });
assert.equal(replaced.replacements, 1);
assert.match((await new DocumentContentService(storage).extract(replaced.file.id)).text, /Updated paragraph/);
const plain = await storage.save({ name: 'contact.txt', mimeType: 'text/plain', content: Buffer.from('Contact me@example.com or 010-1234-5678') });
const extracted = await new DocumentContentService(storage).extract(plain.id);
assert.match(extracted.text, /me@example.com/);
const redacted = await new RedactionService(storage).redact({ fileId: plain.id, outputName: 'redacted.docx', rules: ['email', 'phone'] });
assert.equal(redacted.replacements, 2);
const pdf = await PDFDocument.create(); pdf.addPage([200, 200]);
const inputPdf = await storage.save({ name: 'one-page.pdf', mimeType: 'application/pdf', content: await pdf.save() });
const merged = await new PdfService(storage).merge({ fileIds: [inputPdf.id, inputPdf.id], outputName: 'merged.pdf' });
assert.ok((await storage.read(merged.id)).content.length > 0);
const split = await new PdfService(storage).split({ fileId: inputPdf.id, pageNumbers: [1], outputPrefix: 'page' });
assert.equal(split.length, 1);
const rotated = await new PdfService(storage).edit({ fileId: inputPdf.id, outputName: 'rotated.pdf', operation: { kind: 'rotatePages', pageNumbers: [1], degrees: 90 } });
assert.ok((await storage.read(rotated.id)).content.length > 0);
console.log('structured TypeScript backend smoke test passed');
